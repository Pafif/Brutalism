    <h2>What is brutalism</h2>

    <p>
      Brutalism is an architectural style of late modernism (popular mainly from the 1950s to the 1980s)
      characterized by monumental geometric shapes, exposed structural systems, and above all, raw,
      unrefined concrete. The name does not originate from the word &bdquo;brutal&ldquo; meaning cruel,
      but comes from the French phrase b&eacute;ton brut (raw concrete), used by the pioneer of modern
      architecture, Le Corbusier.
    </p>

    <img class="foto-pravo" src="wp-content/themes/prazdna/images/brutalism-1.jpg" alt="Zizkov television tower">

    <p>
      The style expanded after World War II, when there was a need to rebuild destroyed cities quickly
      and cheaply. It became highly popular for public institutions, universities, government complexes,
      and housing estates. Although criticized in the late 20th century as cold and repulsive, it is
      currently experiencing an aesthetic renaissance, and many buildings are now protected landmarks.
    </p>

